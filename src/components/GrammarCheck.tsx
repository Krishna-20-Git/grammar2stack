import { useMemo } from 'react';
import { compareWithTarget } from '../core';
import { useLab } from '../hooks/useLab';

const MAX_STRINGS = 520; // keeps the check fast: every string up to the longest length that fits this budget
const SHOW = 10;

/**
 * Checks the productions currently applied against the language the person described:
 * every string over the alphabet up to a length is run through the PDA and compared with
 * the description. Differences are listed as clickable counterexamples.
 */
export function GrammarCheck() {
  const lab = useLab();
  const { g, pda, target } = lab;

  const res = useMemo(() => (target ? compareWithTarget(g, pda, target.sigma, target.accepts, MAX_STRINGS) : null), [g, pda, target]);

  if (!target || !res) return null;
  const ok = res.extra.length === 0 && res.missing.length === 0 && res.unknown.length === 0;

  const Chips = ({ words }: { words: string[] }) => (
    <div className="flex flex-wrap gap-1.5">
      {words.slice(0, SHOW).map((w) => (
        <button key={w} className="btn min-h-[30px] px-2 font-mono text-xs" title="Run this string"
          onClick={() => { lab.setInput(w); lab.startRun(); window.scrollTo({ top: 0, behavior: 'smooth' }); }}>{w || 'ε'}</button>
      ))}
      {words.length > SHOW && <span className="self-center text-xs text-slate">+{words.length - SHOW} more</span>}
    </div>
  );

  return (
    <div className={`flex flex-col gap-2 rounded-md border px-3 py-3 ${ok ? 'border-lime/50 bg-lime/[0.06]' : 'border-danger/50 bg-danger/[0.06]'}`} role="status" aria-live="polite">
      <div className="label">Target language</div>
      <p className="text-sm text-ink">Strings over {'{'}{res.sigma.join(', ')}{'}'} that {target.summary}.</p>
      {ok ? (
        <p className="text-sm text-lime">
          ✓ Your productions generate exactly this language for all {res.total} strings of length 0 to {res.maxLen}.
        </p>
      ) : (
        <>
          <p className="text-sm font-semibold text-danger">✗ These productions do not match the description.</p>
          {res.extra.length > 0 && (
            <div className="flex flex-col gap-1">
              <p className="text-xs text-slate">Generated by your grammar, but not in the language ({res.extra.length}):</p>
              <Chips words={res.extra} />
            </div>
          )}
          {res.missing.length > 0 && (
            <div className="flex flex-col gap-1">
              <p className="text-xs text-slate">In the language, but your grammar does not generate them ({res.missing.length}):</p>
              <Chips words={res.missing} />
            </div>
          )}
          {res.unknown.length > 0 && (
            <div className="flex flex-col gap-1">
              <p className="text-xs text-slate">Search limit reached, result unknown ({res.unknown.length}):</p>
              <Chips words={res.unknown} />
            </div>
          )}
          <p className="text-xs text-slate">Click a string to run it. The shortest counterexamples are listed first.</p>
        </>
      )}
      <p className="text-xs text-slate-deep">Checked every string up to length {res.maxLen}. That is strong evidence, not a proof of equivalence.</p>
    </div>
  );
}
